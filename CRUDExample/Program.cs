using ServiceContracts;
using Services;
using Entities;
using Microsoft.EntityFrameworkCore;
using MySql.EntityFrameworkCore;

var builder = WebApplication.CreateBuilder(args);
builder.Services.AddControllersWithViews();

//add services into IoC container
builder.Services.AddSingleton<ICountriesService, CountriesService>();
builder.Services.AddSingleton<IPersonsService, PersonsService>();

builder.Services.AddDbContext<PersonsDbContext>(options =>
{
    options.UseMySQL();
});

var app = builder.Build();

if (app.Environment.IsDevelopment())
{
    app.UseDeveloperExceptionPage();
}

app.UseStaticFiles();
app.UseRouting();
app.MapControllers();
app.Run();

//EntityFrameworkCore

/*
 * Pros and cons of EntityFrameworkCore
 *
 * --> Pros
 * * Shorter Code;
 * * Strongly-Typed (The collumns as created as propertirs in model class; so the Intellisense offers collumn of the table as propertirs, while writing the code)
 *
 * --> Cons
 * * Performance (EFCore performs slower than ADO.NET, so ADO>NET or its alternatives are recommended for larger & high-traffic applications).
 */
/*

/*
  EFCore Approches
  
  --> DBFirst Approach
    * Design-Time: DB --Generate--> Entity Model Classes
    * Run-Time: Entity Model Classes --Access--> DB

    * Suitable if you have an existing database, or it was generated by DBA's, separately
    * Manual changes to DB can be done independently
    * Stored procedures are to be written as a part of C# code
 * 

  --> Code-First Approach
    * Design-Time: Entity Model Classes --Generate--> DB
    * Run-Time: Entity Model Classes --Access--> DB
    
    * Used when creating new databases
    * Manual changes to DB will be most probably lost because your code defines the database
    * Stored procedures, indexes, triggers etc., can be created with T-SQL independently
*/